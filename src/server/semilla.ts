function usuario(
  datos: Omit<UsuarioInterno, "salt" | "hash" | "ejemplo">,
  clavePlana: string,
): UsuarioInterno {
  const clave = crearClave(clavePlana)
  return { ...datos, ejemplo: true, ...clave }
}

